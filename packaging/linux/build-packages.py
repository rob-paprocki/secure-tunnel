"""Builds the Linux packages from the release binaries, on Windows, macOS or Linux.

    python -I packaging/linux/build-packages.py

Needs the binaries first (from the app folder):
    cargo zigbuild --release --target x86_64-unknown-linux-gnu.2.31
    cargo zigbuild --release --target aarch64-unknown-linux-gnu.2.31
and the packagers: cargo install cargo-deb cargo-generate-rpm

Writes dist/linux/:
    secure-tunnel_<ver>-1_amd64.deb / _arm64.deb      Debian, Ubuntu, Mint, Pop!_OS, Kali...
    secure-tunnel-<ver>-1.x86_64.rpm / .aarch64.rpm   Fedora, RHEL/Rocky/Alma, openSUSE
    secure-tunnel-<ver>-1-x86_64.pkg.tar.zst / -aarch64  Arch, Manjaro, EndeavourOS
    secure-tunnel-<ver>-linux-<arch>.tar.gz           anything else (install.sh inside)
    SHA256SUMS
"""
import gzip
import hashlib
import io
import os
import shutil
import subprocess
import sys
import tarfile
import time
import tomllib
from compression import zstd
from pathlib import Path

APP = Path(__file__).resolve().parents[2]
OUT = APP / "dist" / "linux"
TARGET = Path(os.environ.get("CARGO_TARGET_DIR") or APP / "target")
LINUX = APP / "packaging" / "linux"
ARCHES = {"x86_64": ("amd64", "x86_64"), "aarch64": ("arm64", "aarch64")}  # rust arch -> (deb, rpm/arch)

meta = tomllib.loads((APP / "Cargo.toml").read_text(encoding="utf-8"))["package"]
VER = meta["version"]
NOW = int(time.time())


def run(*cmd: str) -> None:
    print("+", " ".join(cmd))
    subprocess.run(cmd, cwd=APP, check=True)


def files(arch: str) -> list[tuple[str, Path, int]]:
    """(installed path, source, mode) for everything a package holds."""
    out = [
        ("usr/bin/secure-tunnel", TARGET / f"{arch}-unknown-linux-gnu/release/secure-tunnel", 0o755),
        ("usr/share/applications/secure-tunnel.desktop", LINUX / "secure-tunnel.desktop", 0o644),
        ("usr/share/licenses/secure-tunnel/LICENSE", APP / "LICENSE", 0o644),
        ("usr/share/licenses/secure-tunnel/THIRD_PARTY.md", APP / "THIRD_PARTY.md", 0o644),
    ]
    for s in (48, 128, 256):
        out.append((f"usr/share/icons/hicolor/{s}x{s}/apps/secure-tunnel.png", LINUX / f"icons/{s}x{s}/secure-tunnel.png", 0o644))
    return out


def tar_add(t: tarfile.TarFile, name: str, data: bytes, mode: int) -> None:
    info = tarfile.TarInfo(name)
    info.size, info.mode, info.mtime = len(data), mode, NOW
    info.uid = info.gid = 0
    info.uname = info.gname = "root"
    t.addfile(info, io.BytesIO(data))


def tar_dirs(t: tarfile.TarFile, paths: list[str], seen: set[str]) -> None:
    for p in paths:
        parts = p.split("/")[:-1]
        for i in range(1, len(parts) + 1):
            d = "/".join(parts[:i])
            if d not in seen:
                seen.add(d)
                info = tarfile.TarInfo(d)
                info.type, info.mode, info.mtime = tarfile.DIRTYPE, 0o755, NOW
                info.uname = info.gname = "root"
                t.addfile(info)


def arch_pkg(arch: str) -> Path:
    """An Arch package: .PKGINFO, .MTREE and the files, zstd-compressed."""
    _, carch = ARCHES[arch]
    entries = files(arch)
    size = sum(src.stat().st_size for _, src, _ in entries)
    pkginfo = "\n".join(
        [
            "# Generated by build-packages.py",
            "pkgname = secure-tunnel",
            "pkgbase = secure-tunnel",
            f"pkgver = {VER}-1",
            "pkgdesc = Desktop VPN client for WireGuard profiles",
            f"builddate = {NOW}",
            "packager = Secure Tunnel maintainers",
            f"size = {size}",
            f"arch = {carch}",
            "license = GPL-3.0-or-later",
        ]
        + [
            f"depend = {d}"
            for d in "glibc libglvnd libxkbcommon libx11 libxcursor libxrandr libxi wayland iproute2 nftables polkit procps-ng xdg-utils".split()
        ]
        + ["optdepend = libsecret: keep the profile key in the desktop keyring", "optdepend = xdg-desktop-portal: native file dialogs"]
    ) + "\n"
    # .MTREE lets `pacman -Qkk` check the installed files.
    mtree = ["#mtree", "/set type=file uid=0 gid=0 mode=644", f"./.PKGINFO time={NOW} size={len(pkginfo)} md5digest={hashlib.md5(pkginfo.encode()).hexdigest()} sha256digest={hashlib.sha256(pkginfo.encode()).hexdigest()}"]
    seen: set[str] = set()
    for dest, src, mode in entries:
        parts = dest.split("/")[:-1]
        for i in range(1, len(parts) + 1):
            d = "/".join(parts[:i])
            if d not in seen:
                seen.add(d)
                mtree.append(f"./{d} time={NOW} mode=755 type=dir")
        data = src.read_bytes()
        mtree.append(
            f"./{dest} time={NOW} mode={mode:o} size={len(data)} md5digest={hashlib.md5(data).hexdigest()} sha256digest={hashlib.sha256(data).hexdigest()}"
        )
    mtree_gz = gzip.compress(("\n".join(mtree) + "\n").encode(), mtime=NOW)
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.GNU_FORMAT) as t:
        tar_add(t, ".PKGINFO", pkginfo.encode(), 0o644)
        tar_add(t, ".MTREE", mtree_gz, 0o644)
        tar_dirs(t, [d for d, _, _ in entries], set())
        for dest, src, mode in entries:
            tar_add(t, dest, src.read_bytes(), mode)
    out = OUT / f"secure-tunnel-{VER}-1-{carch}.pkg.tar.zst"
    out.write_bytes(zstd.compress(buf.getvalue(), level=19))
    return out


def tarball(arch: str) -> Path:
    root = f"secure-tunnel-{VER}-linux-{arch}"
    out = OUT / f"{root}.tar.gz"
    with tarfile.open(out, "w:gz") as t:
        tar_add(t, f"{root}/secure-tunnel", (TARGET / f"{arch}-unknown-linux-gnu/release/secure-tunnel").read_bytes(), 0o755)
        tar_add(t, f"{root}/install.sh", (LINUX / "install.sh").read_bytes().replace(b"\r\n", b"\n"), 0o755)
        tar_add(t, f"{root}/secure-tunnel.desktop", (LINUX / "secure-tunnel.desktop").read_bytes(), 0o644)
        tar_add(t, f"{root}/LICENSE", (APP / "LICENSE").read_bytes(), 0o644)
        tar_add(t, f"{root}/THIRD_PARTY.md", (APP / "THIRD_PARTY.md").read_bytes(), 0o644)
        for s in (48, 128, 256):
            tar_add(t, f"{root}/icons/{s}x{s}/secure-tunnel.png", (LINUX / f"icons/{s}x{s}/secure-tunnel.png").read_bytes(), 0o644)
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    made = []
    for arch, (deb, rpm) in ARCHES.items():
        triple = f"{arch}-unknown-linux-gnu"
        if not (TARGET / f"{triple}/release/secure-tunnel").exists():
            sys.exit(f"missing target/{triple}/release/secure-tunnel: build it first (see the top of this file)")
        run("cargo", "deb", "--no-build", "--no-strip", "--target", triple, "--output", str(OUT / f"secure-tunnel_{VER}-1_{deb}.deb"))
        run("cargo", "generate-rpm", "--target", triple, "--arch", rpm, "--output", str(OUT / f"secure-tunnel-{VER}-1.{rpm}.rpm"))
        made.append(arch_pkg(arch))
        made.append(tarball(arch))
    sums = []
    for f in sorted(OUT.iterdir()):
        sums.append(f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.name}")
    (OUT / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8", newline="\n")
    shutil.copy(LINUX / "PKGBUILD", OUT / "PKGBUILD")
    print("\n".join(sums))


if __name__ == "__main__":
    os.chdir(APP)
    main()
